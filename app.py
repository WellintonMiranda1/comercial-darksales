@app.post('/clients/<int:client_id>/payment')
def payment_add(client_id):
    client=own_client(client_id)
    try:
        if client['status'] in ('cancelled','lost'):
            raise ValueError('Reabra a negociação antes de confirmar um pagamento.')
        if client['cycle'] not in CYCLES:
            raise ValueError('Tipo de contrato inválido.')
        paid_on=request.form.get('paid_on') or today()
        received=date.fromisoformat(paid_on)
        if received > date.today():
            raise ValueError('Não é possível confirmar pagamento com data futura.')
        if client['monthly_price_cents'] <= 0:
            raise ValueError('Informe um valor mensal maior que zero antes de confirmar pagamento.')
        with db() as c:
            # O servidor controla a competência. Não aceitar início digitado pelo navegador.
            last=c.execute('''SELECT * FROM payments WHERE client_id=?
                              ORDER BY period_end DESC,id DESC LIMIT 1''',(client_id,)).fetchone()
            if last:
                # Sem duplicar parcelas pagas no primeiro mês.
                # Renovação só pode ser lançada 5 dias antes do final ou depois.
                last_end=date.fromisoformat(last['period_end'])
                if received < last_end - timedelta(days=5):
                    raise ValueError('Este contrato já tem pagamento registrado. A renovação só pode ser confirmada nos 5 dias anteriores ao vencimento.')
                period_start=last['period_end']
            else:
                period_start=client['start_date'] or paid_on
            created=record_first_payment(c,client_id,client['seller_id'],client['tier'],client['cycle'],
                                         client['monthly_price_cents'],period_start,paid_on)
            if not created:
                raise ValueError('Este período já possui pagamento. Nenhuma nova comissão foi gerada.')
            end=contract_end(period_start,client['cycle'])
            c.execute("UPDATE clients SET status='active',trial_end=NULL,start_date=COALESCE(start_date,?),due_date=?,updated_at=CURRENT_TIMESTAMP WHERE id=?",
                      (period_start,end,client_id))
        flash('Pagamento registrado uma única vez e comissão gerada.','success')
    except (sqlite3.IntegrityError, psycopg.IntegrityError):
        flash('Pagamento repetido: este período já está registrado.','error')
    except (ValueError,TypeError) as e:
        flash(str(e),'error')
    return redirect(url_for('client_detail',client_id=client_id))


@app.post('/clients/<int:client_id>/cancel')
def client_cancel(client_id):
    """Cancel an owned client's subscription, preserving payments and commissions."""
    client = own_client(client_id)  # Admin: any client; seller: their own only.
    if request.form.get('confirm_cancel') != 'CANCELAR':
        abort(400, 'Confirmação necessária para cancelar a assinatura.')
    if client['status'] == 'cancelled':
        flash('Esta assinatura já está cancelada.', 'error')
    else:
        with db() as c:
            # Recheck ownership in the update so reassignment cannot authorize
            # cancelling a client that has moved to another seller.
            if get_user()['role'] == 'admin':
                cur = c.execute("UPDATE clients SET status='cancelled',updated_at=CURRENT_TIMESTAMP WHERE id=? AND status!='cancelled'", (client_id,))
            else:
                cur = c.execute("UPDATE clients SET status='cancelled',updated_at=CURRENT_TIMESTAMP WHERE id=? AND seller_id=? AND status!='cancelled'", (client_id,get_user()['id']))
            if not cur.rowcount:
                abort(403, 'Não foi possível cancelar esta assinatura.')
        flash('Assinatura cancelada. Histórico de pagamentos e comissões preservado.', 'success')
    return redirect(url_for('client_detail', client_id=client_id))


